    def _caller_loc(self) -> str:
        try:
            frame = sys._getframe(1)
        except Exception:
            return ""
        script_abs = os.path.normcase(self.script_file) if self.script_file else ""
        runtime_abs = os.path.normcase(os.path.abspath(__file__))
        fallback_loc = ""
        while frame is not None:
            code = frame.f_code
            fn_name = code.co_name
            fname_norm = os.path.normcase(os.path.abspath(code.co_filename))
            is_self_runtime = frame.f_locals.get("self") is self
            if not is_self_runtime:
                if fn_name.startswith("func_"):
                    if fn_name == "func_entry":
                        return f"[L{frame.f_lineno:03d}]"
                    return f"[{fn_name}:L{frame.f_lineno:03d}]"
                if script_abs and fname_norm == script_abs and not fallback_loc:
                    fallback_loc = f"[L{frame.f_lineno:03d}]"
                elif fname_norm != runtime_abs and not fallback_loc:
                    fallback_loc = f"[L{frame.f_lineno:03d}]"
            frame = frame.f_back
        return fallback_loc

    def _init_file_log(self, custom_log_dir: str | None = None) -> None:
        import re as _re

        target_dir = custom_log_dir or os.path.join(self.script_dir, "logs")
        try:
            os.makedirs(target_dir, exist_ok=True)
        except OSError:
            return
        self.log_dir = target_dir
        script_base = (
            os.path.splitext(os.path.basename(self.script_file))[0]
            if self.script_file
            else "amk_script"
        )
        safe_stem = _re.sub(r"[^A-Za-z0-9_.-]+", "_", script_base).strip("_") or "script"
        ts_str = self._start_wall.strftime("%Y%m%d_%H%M%S")
        log_fn = f"{ts_str}_{safe_stem}.log"
        self.log_file_path = os.path.join(target_dir, log_fn)
        try:
            self._log_fp = open(self.log_file_path, "w", encoding="utf-8")
        except OSError:
            self.log_file_path = None
            self._log_fp = None
            return

        host = os.environ.get("COMPUTERNAME") or os.environ.get("HOSTNAME") or "unknown"
        user = os.environ.get("USERNAME") or os.environ.get("USER") or "unknown"
        scr_info = "N/A"
        if sys.platform == "win32" and self._user32 is not None:
            try:
                pw = int(self._user32.GetSystemMetrics(0))
                ph = int(self._user32.GetSystemMetrics(1))
                vx = int(self._user32.GetSystemMetrics(SM_XVIRTUALSCREEN))
                vy = int(self._user32.GetSystemMetrics(SM_YVIRTUALSCREEN))
                vw = int(self._user32.GetSystemMetrics(SM_CXVIRTUALSCREEN))
                vh = int(self._user32.GetSystemMetrics(SM_CYVIRTUALSCREEN))
                scr_info = f"{pw}x{ph} (virtual: {vx},{vy} -> {vw}x{vh})"
            except Exception:
                pass

