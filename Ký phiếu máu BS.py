    # Screen capture & hybrid template matching
    # -----------------------------------------------------------------------

    def _grab_screen_bgr(
        self, region: tuple[int, int, int, int] | None = None
    ) -> tuple[int, int, np.ndarray]:
        if region is None:
            left = 0
            top = 0
            w = int(self._user32.GetSystemMetrics(0))
            h = int(self._user32.GetSystemMetrics(1))
        else:
            vx = int(self._user32.GetSystemMetrics(76))
            vy = int(self._user32.GetSystemMetrics(77))
            vw = int(self._user32.GetSystemMetrics(78))
            vh = int(self._user32.GetSystemMetrics(79))
            l, t, r, b = (int(v) for v in region)
            left = max(vx, min(vx + vw - 1, l))
            top = max(vy, min(vy + vh - 1, t))
            right = max(left + 1, min(vx + vw, r))
            bottom = max(top + 1, min(vy + vh, b))
            w = right - left
            h = bottom - top

        hdc_screen = self._user32.GetDC(None)
        if not hdc_screen:
            raise RuntimeError("GetDC(0) failed")
        hdc_mem = None
        hbmp = None
        old_obj = None
        try:
            hdc_mem = self._gdi32.CreateCompatibleDC(hdc_screen)
            hbmp = self._gdi32.CreateCompatibleBitmap(hdc_screen, w, h)
            old_obj = self._gdi32.SelectObject(hdc_mem, hbmp)
            ok = self._gdi32.BitBlt(hdc_mem, 0, 0, w, h, hdc_screen, left, top, SRCCOPY)
            if not ok:
                raise RuntimeError("BitBlt failed")

            bmi = BITMAPINFO()
            bmi.bmiHeader.biSize = ctypes.sizeof(BITMAPINFOHEADER)
            bmi.bmiHeader.biWidth = w
            bmi.bmiHeader.biHeight = -h  # top-down DIB
            bmi.bmiHeader.biPlanes = 1
            bmi.bmiHeader.biBitCount = 32
            bmi.bmiHeader.biCompression = 0  # BI_RGB

            buf = (ctypes.c_ubyte * (w * h * 4))()
            rows = self._gdi32.GetDIBits(hdc_mem, hbmp, 0, h, buf, ctypes.byref(bmi), DIB_RGB_COLORS)
            if rows != h:
                raise RuntimeError(f"GetDIBits returned {rows} rows, expected {h}")
            bgra = np.frombuffer(buf, dtype=np.uint8).reshape((h, w, 4))
            return left, top, bgra[:, :, :3].copy()
        finally:
            if hdc_mem and old_obj:
                self._gdi32.SelectObject(hdc_mem, old_obj)
            if hbmp:
                self._gdi32.DeleteObject(hbmp)
            if hdc_mem:
                self._gdi32.DeleteDC(hdc_mem)
            self._user32.ReleaseDC(None, hdc_screen)

    def rect(self, x: int | float, y: int | float, w: int | float, h: int | float) -> tuple[int, int, int, int]:
        return (int(x), int(y), int(w), int(h))

    def capture_screen_image(
        self, rect: tuple[int, int, int, int], capture_cursor: bool = False
    ) -> AmkImage:
        self.check_stop()
        x, y, w, h = rect
        self._step(f"CaptureScreen(rect={rect}, cursor={bool(capture_cursor)})")
        if self.dry_run:
            return AmkImage(np.zeros((max(1, h), max(1, w), 3), dtype=np.uint8))
        _, _, bgr = self._grab_screen_bgr((x, y, x + w, y + h))
        return AmkImage(bgr)

    def find_image(
        self,
        templates: list[tuple[str, float]],
        *,
        region: tuple[int, int, int, int] | None = None,
        timeout: int | float = 10,
        timeout_unit: str = "s",
        fdo: str = "click",
        tdo: str | None = None,
        is_if: bool = False,
        name: str = "",
    ) -> bool:
        self.check_stop()
        resolved_templates: list[tuple[str, np.ndarray, float]] = []
        for key, sml in templates:
            if key not in self._templates:
                raise KeyError(f"Missing embedded template {key!r}")
            resolved_templates.append((key, self._templates[key], float(sml)))

        loc = self._caller_loc()
        prefix = f"{loc} " if loc else ""
        keys = [k for k, _ in templates]
        label = f"{name!r}, " if name else ""
        desc = f"find_image({label}{keys}, region={region}, tout={timeout}{timeout_unit}, fdo={fdo})"
        self.last_step = f"{prefix}{desc}".strip()
        self.last_match_detail = ""

        if self.dry_run:
            self._step_count += 1
            self._write_log_line(self.last_step)
            if not self.quiet:
                print(f"[DRY-RUN] {self.last_step}", flush=True)
            return True

        self._step_count += 1
        timeout_sec = (
            -1.0
            if float(timeout) < 0
            else (float(timeout) / 1000.0 if timeout_unit == "ms" else float(timeout))
        )
        start = time.monotonic()
        last_hb = start

        while True:
            self.check_stop()
            rx, ry, screen_bgr = self._grab_screen_bgr(region)
            best_key = ""
            best_score = -1000.0
            best_sml = 95.0
            best_cx, best_cy = rx, ry

            for key, tmpl_bgr, sml in resolved_templates:
                matched, (mx, my), score_pct = match_template_hybrid(screen_bgr, tmpl_bgr, sml)
                th, tw = tmpl_bgr.shape[:2]
                cx = rx + mx + tw // 2
                cy = ry + my + th // 2
                if score_pct > best_score:
                    best_key = key
                    best_score = score_pct
                    best_sml = sml
                    best_cx, best_cy = cx, cy
                if matched:
                    self.last_match_detail = (
                        f"khớp {key}={score_pct:.1f}% (yêu cầu {sml:.0f}%) tại ({cx}, {cy})"
                    )
                    found_msg = (
                        f"{prefix}{desc} -> THẤY {key} ({score_pct:.1f}%) tại ({cx}, {cy}) [{fdo}]"
                    )
                    self._write_log_line(found_msg)
                    if not self.quiet:
                        print(found_msg, flush=True)
                    if fdo == "click":
                        self._mouse_move_abs_raw(cx, cy)
                        self._mouse_click_raw(0, 0)
                    elif fdo == "move":
                        self._mouse_move_abs_raw(cx, cy)
                    return True

            if best_key:
                self.last_match_detail = (
                    f"tốt nhất: {best_key}={max(0.0, best_score):.1f}% "
                    f"(yêu cầu {best_sml:.0f}%) tại ({best_cx}, {best_cy})"
                )

            now = time.monotonic()
            if timeout_sec >= 0 and (now - start) >= timeout_sec:
                break
            if (now - last_hb) >= 2.0:
                hb_msg = (
                    f"{prefix}Đang chờ ảnh {keys} ({now - start:.1f}s; {self.last_match_detail}) — nhấn F12 để dừng"
                )
                self._write_log_line(hb_msg)
                if not self.quiet:
                    print(hb_msg, flush=True)
                last_hb = now
            self._sleep_ms_raw(30)

        detail_msg = f" ({self.last_match_detail})" if self.last_match_detail else ""
        miss_msg = f"{prefix}{desc} -> KHÔNG THẤY sau {timeout}{timeout_unit}{detail_msg}"
        self._write_log_line(miss_msg)
        if not self.quiet:
            print(miss_msg, flush=True)

        if is_if:
            return False
        if tdo == "continue":
            return False
        if tdo == "stop no tip":
            raise AmkStopScript(f"Image not found (stop no tip): {name}", silent=True)
        self._capture_error_screenshot(
            region=region,
            best_pt=(best_cx, best_cy) if best_key else None,
            label=str(name or keys),
        )
        raise AmkStopScript(
            f"Không tìm thấy hình ảnh {name or keys} tại {loc or 'script'} sau {timeout}{timeout_unit}{detail_msg}.",
            silent=False,
        )

