    def _find_window_by_title(self, title: str) -> int | None:
        target = title.lower()
        exact_match: list[int] = []
        substr_match: list[int] = []

        WNDENUMPROC = ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)

        def callback(hwnd: int, _lparam: int) -> bool:
            if not self._user32.IsWindowVisible(hwnd):
                return True
            length = self._user32.GetWindowTextLengthW(hwnd)
            if length <= 0:
                return True
            buf = ctypes.create_unicode_buffer(length + 1)
            self._user32.GetWindowTextW(hwnd, buf, length + 1)
            wtitle = buf.value
            if wtitle.lower() == target:
                exact_match.append(hwnd)
                return False
            if target in wtitle.lower():
                substr_match.append(hwnd)
            return True

        cb = WNDENUMPROC(callback)
        self._user32.EnumWindows(cb, 0)
        if exact_match:
            return exact_match[0]
        if substr_match:
            return substr_match[0]
        return None

    def _activate_window(self, hwnd: int) -> None:
        if self._user32.IsIconic(hwnd):
            self._user32.ShowWindow(hwnd, SW_RESTORE)
        fg = self._user32.GetForegroundWindow()
        cur_tid = self._kernel32.GetCurrentThreadId()
        fg_tid = self._user32.GetWindowThreadProcessId(fg, None) if fg else 0
        attached = False
        try:
            if fg_tid and fg_tid != cur_tid:
                attached = bool(self._user32.AttachThreadInput(cur_tid, fg_tid, True))
            self._user32.BringWindowToTop(hwnd)
            self._user32.SetForegroundWindow(hwnd)
        finally:
            if attached:
                self._user32.AttachThreadInput(cur_tid, fg_tid, False)

    def wait_window(
        self,
        title: str,
        *,
        appear: bool = True,
        timeout: int | float = 10,
        unit: str = "s",
        switch: bool = True,
    ) -> bool:
        self.check_stop()
        loc = self._caller_loc()
        prefix = f"{loc} " if loc else ""
        desc = f"wait_window({title!r}, appear={appear}, tout={timeout}{unit}, switch={switch})"
        self.last_step = f"{prefix}{desc}".strip()
        self.last_match_detail = ""
        if self.dry_run:
            self._step_count += 1
            self._write_log_line(self.last_step)
            if not self.quiet:
                print(f"[DRY-RUN] {self.last_step}", flush=True)
            return True

        self._step_count += 1
        timeout_sec = (
            -1.0
            if float(timeout) < 0
            else (float(timeout) / 1000.0 if unit == "ms" else float(timeout))
        )
        start = time.monotonic()
        last_hb = start

        while True:
            self.check_stop()
            hwnd = self._find_window_by_title(title)
            if appear and hwnd is not None:
                if switch:
                    self._activate_window(hwnd)
                ok_msg = f"{prefix}{desc} -> OK"
                self._write_log_line(ok_msg)
                if not self.quiet:
                    print(ok_msg, flush=True)
                return True
            if (not appear) and hwnd is None:
                ok_msg = f"{prefix}{desc} -> OK"
                self._write_log_line(ok_msg)
                if not self.quiet:
                    print(ok_msg, flush=True)
                return True
            now = time.monotonic()
            if timeout_sec >= 0 and (now - start) >= timeout_sec:
                tout_msg = f"{prefix}{desc} -> HẾT THỜI GIAN CHỜ"
                self._write_log_line(tout_msg)
                if not self.quiet:
                    print(tout_msg, flush=True)
                return False
            if (now - last_hb) >= 2.0:
                state_txt = "xuất hiện" if appear else "đóng"
                hb_msg = (
                    f"{prefix}Đang chờ cửa sổ {title!r} {state_txt} ({now - start:.1f}s) — nhấn F12 để dừng"
                )
                self._write_log_line(hb_msg)
                if not self.quiet:
                    print(hb_msg, flush=True)
                last_hb = now
            self._sleep_ms_raw(30)

    def message_box(self, text: Any) -> None:
        self.check_stop()
        msg = "" if text is None else str(text)
        self._step(f"MessageBox({msg!r})")
        if self.dry_run:
            return
        res = self._user32.MessageBoxW(
            None, msg, "AMK Python Automation", MB_OKCANCEL | MB_ICONINFORMATION | MB_TOPMOST
        )
        if res == IDCANCEL:
            raise AmkStopScript("Người dùng đã bấm Cancel.", silent=True)

