class AmkImage:
    """In-memory captured screen region supporting exact pixel equality."""

    def __init__(self, bgr: np.ndarray) -> None:
        self.data = bgr

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, AmkImage):
            return False
        if self.data.shape != other.data.shape:
            return False
        return bool(np.array_equal(self.data, other.data))


def _enable_dpi_awareness() -> None:
    if sys.platform != "win32":
        return
    try:
        user32 = ctypes.windll.user32
        user32.SetProcessDpiAwarenessContext.argtypes = [ctypes.c_void_p]
        user32.SetProcessDpiAwarenessContext.restype = wintypes.BOOL
        if user32.SetProcessDpiAwarenessContext(ctypes.c_void_p(-4)):
            return
    except Exception:
        pass
    try:
        shcore = ctypes.windll.shcore
        shcore.SetProcessDpiAwareness(2)
        return
    except Exception:
        pass
    try:
        ctypes.windll.user32.SetProcessDPIAware()
    except Exception:
        pass


def _decode_template_b64(b64_str: str) -> np.ndarray:
    png_bytes = base64.b64decode(b64_str)
    arr = np.frombuffer(png_bytes, dtype=np.uint8)
    bgr = cv2.imdecode(arr, cv2.IMREAD_COLOR)
    if bgr is None:
        raise ValueError("Failed to decode embedded PNG template")
    return bgr


def match_template_hybrid(
    screen_bgr: np.ndarray, tmpl_bgr: np.ndarray, sml: float
) -> tuple[bool, tuple[int, int], float]:
    """Match a template against a screen BGR image using hybrid CCOEFF/SQDIFF logic.

    Returns (matched, (match_x, match_y), confidence_0_to_100).
    """
    sh, sw = screen_bgr.shape[:2]
    th, tw = tmpl_bgr.shape[:2]
    if sh < th or sw < tw or th <= 0 or tw <= 0:
        return False, (0, 0), 0.0

    # Per-channel spatial standard deviation catches solid colored templates
    # (e.g., light yellow [224,255,255] has spatial std=0.0 per channel,
    # even though cross-channel std is 14.6).
    ch_std_max = float(tmpl_bgr.std(axis=(0, 1)).max())
    if ch_std_max < 8.0:
        res = cv2.matchTemplate(screen_bgr, tmpl_bgr, cv2.TM_SQDIFF)
        min_val, _, min_loc, _ = cv2.minMaxLoc(res)
        mx, my = min_loc
        patch = screen_bgr[my : my + th, mx : mx + tw]
        diff = np.abs(patch.astype(np.float32) - tmpl_bgr.astype(np.float32))
        rmse = float(math.sqrt(max(0.0, min_val) / float(tmpl_bgr.size)))
        max_diff = float(diff.max())
        sim_score = 100.0 * (1.0 - rmse / 255.0)
        req_sim = max(float(sml), 96.0 if sml >= 95 else float(sml))
        base_tol = 8.0 if ch_std_max < 1.5 else 12.0
        req_max_diff = base_tol if sml >= 95 else float(int((100.0 - float(sml)) * 2.55) + base_tol)
        matched = (sim_score >= req_sim) and (max_diff <= req_max_diff)
        if not matched and sim_score >= float(sml):
            sim_score = min(float(sml) - 0.5, 100.0 * (1.0 - max_diff / 255.0))
        return matched, (mx, my), max(0.0, sim_score)

    res = cv2.matchTemplate(screen_bgr, tmpl_bgr, cv2.TM_CCOEFF_NORMED)
    _, max_val, _, max_loc = cv2.minMaxLoc(res)
    mx, my = max_loc
    patch = screen_bgr[my : my + th, mx : mx + tw]
    diff = patch.astype(np.float32) - tmpl_bgr.astype(np.float32)
    rmse = float(math.sqrt(float(np.mean(diff * diff))))
    max_rmse = 25.0 if sml >= 95 else (100.0 - float(sml)) * 3.0 + 35.0
    cc_score = float(max_val) * 100.0
    matched = (float(max_val) >= float(sml) / 100.0) and (rmse <= max_rmse)
    if not matched and float(max_val) >= float(sml) / 100.0:
        res_sq = cv2.matchTemplate(screen_bgr, tmpl_bgr, cv2.TM_SQDIFF)
        min_val, _, min_loc, _ = cv2.minMaxLoc(res_sq)
        sx, sy = min_loc
        sq_rmse = float(math.sqrt(max(0.0, min_val) / float(tmpl_bgr.size)))
        sq_cc = float(res[sy, sx]) * 100.0
        if (sq_cc >= float(sml)) and (sq_rmse <= max_rmse):
            return True, (sx, sy), sq_cc
        cc_score = min(float(sml) - 0.5, 100.0 * (1.0 - rmse / 255.0))
    return matched, (mx, my), max(0.0, cc_score)


def _parse_vk(vk: int | str) -> int:
    if isinstance(vk, int):
        return vk
    s = str(vk).strip()
    if s.lower().startswith("0x"):
        return int(s, 16)
    return int(s)


def _to_number_if_possible(val: Any) -> tuple[bool, int | float]:
    if isinstance(val, bool):
        return False, 0
    if isinstance(val, (int, float)):
        return True, val
    if isinstance(val, str):
        s = val.strip()
        if not s:
            return False, 0
        try:
            return True, int(s)
        except ValueError:
            try:
                f = float(s)
                if math.isfinite(f):
                    return True, f
            except ValueError:
                pass
    return False, 0


