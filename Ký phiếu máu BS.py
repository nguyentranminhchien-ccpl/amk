def run_entry(
    entry_fn: Callable[[AmkRuntime], None],
    templates_b64: dict[str, str],
    description: str,
    script_file: str,
) -> int:
    import traceback as _traceback

    parser = build_arg_parser(description)
    args = parser.parse_args()
    abs_script = os.path.abspath(script_file)
    script_dir = os.path.dirname(abs_script)
    enable_file_log = (not args.no_log) and (
        (not args.dry_run) or args.save_log or bool(args.log_dir)
    )
    rt = AmkRuntime(
        templates_b64,
        dry_run=args.dry_run,
        excel_override=args.excel,
        delay_scale=args.delay_scale,
        verbose=args.verbose,
        quiet=args.quiet,
        start_row=args.start_row,
        script_dir=script_dir,
        script_file=abs_script,
        log_dir=args.log_dir,
        enable_file_log=enable_file_log,
    )
    if args.start_delay > 0 and not args.dry_run:
        print(f"Bắt đầu sau {args.start_delay:.1f} giây... (Nhấn F12 bất kỳ lúc nào để dừng khẩn cấp)")
        rt.sleep_ms(args.start_delay * 1000.0)
    try:
        entry_fn(rt)
        saved_log = rt.finalize_log("SUCCESS")
        if saved_log and not args.quiet:
            print(f"[LOG] Đã lưu nhật ký chạy tại: {saved_log}")
    except AmkStopScript as stop:
        rt.release_held_inputs()
        stop_msg = str(stop)
        status = "STOPPED_SILENT" if stop.silent else "STOPPED"
        saved_log = rt.finalize_log(status, error_msg=stop_msg)
        if not stop.silent and stop_msg:
            print(f"[DỪNG] {stop_msg}")
            if rt.last_step:
                print(f"[VỊ TRÍ DỪNG] {rt.last_step}")
            if rt.last_match_detail:
                print(f"[CHI TIẾT ẢNH] {rt.last_match_detail}")
            if saved_log:
                print(f"[LOG] Nhật ký chi tiết: {saved_log}")
            if rt.error_screenshot_path:
                print(f"[LOG] Ảnh màn hình lúc dừng: {rt.error_screenshot_path}")
        return 0
    except KeyboardInterrupt:
        rt.release_held_inputs()
        saved_log = rt.finalize_log("STOPPED_CTRL_C", error_msg="Đã hủy bởi người dùng (Ctrl+C).")
        print("[DỪNG] Đã hủy bởi người dùng (Ctrl+C).")
        if rt.last_step:
            print(f"[VỊ TRÍ DỪNG] {rt.last_step}")
        if rt.last_match_detail:
            print(f"[CHI TIẾT ẢNH] {rt.last_match_detail}")
        if saved_log:
            print(f"[LOG] Nhật ký chi tiết: {saved_log}")
        return 0
    except Exception as exc:
        rt.release_held_inputs()
        rt._capture_error_screenshot(label=type(exc).__name__)
        tb_str = _traceback.format_exc()
        saved_log = rt.finalize_log("ERROR_EXCEPTION", error_msg=f"{type(exc).__name__}: {exc}", tb_text=tb_str)
        if rt.last_step:
            print(f"[LỖI TẠI BƯỚC] {rt.last_step}: {exc}", file=sys.stderr)
        if saved_log:
            print(f"[LOG] Nhật ký lỗi chi tiết: {saved_log}", file=sys.stderr)
        if rt.error_screenshot_path:
            print(f"[LOG] Ảnh màn hình lúc lỗi: {rt.error_screenshot_path}", file=sys.stderr)
        raise
    finally:
        rt.release_held_inputs()
    return 0

