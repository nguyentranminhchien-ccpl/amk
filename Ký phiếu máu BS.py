# Entry point
# ===========================================================================

def main() -> int:
    return run_entry(
        func_entry,
        TEMPLATES,
        'Converted AMK script: Ký phiếu máu BS.amk',
        __file__,
    )


if __name__ == "__main__":
    sys.exit(main())
