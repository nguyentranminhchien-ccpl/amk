    def key_press(
        self,
        vk: int | str,
        ctrl: bool = False,
        shift: bool = False,
        alt: bool = False,
        win: bool = False,
        count: int = 1,
    ) -> None:
        self.check_stop()
        code = _parse_vk(vk)
        mods = [m for m, on in [("CTRL", ctrl), ("SHIFT", shift), ("ALT", alt), ("WIN", win)] if on]
        mod_str = f", mods={mods}" if mods else ""
        cnt_str = f", count={count}" if int(count) != 1 else ""
        self._step(f"key_press(0x{code:02X}{mod_str}{cnt_str})")
        if self.dry_run:
            return
        self._key_press_raw(code, ctrl=ctrl, shift=shift, alt=alt, win=win, count=count)

    def _set_clipboard_text(self, text: str) -> None:
        data = (text + "\0").encode("utf-16-le")
        for _ in range(8):
            if self._user32.OpenClipboard(None):
                break
            time.sleep(0.02)
        else:
            raise RuntimeError("Không thể mở Clipboard để dán văn bản")
        try:
            self._user32.EmptyClipboard()
            hmem = self._kernel32.GlobalAlloc(GMEM_MOVEABLE, len(data))
            if not hmem:
                raise MemoryError("GlobalAlloc failed")
            ptr = self._kernel32.GlobalLock(hmem)
            if not ptr:
                self._kernel32.GlobalFree(hmem)
                raise MemoryError("GlobalLock failed")
            try:
                ctypes.memmove(ptr, data, len(data))
            finally:
                self._kernel32.GlobalUnlock(hmem)
            if not self._user32.SetClipboardData(CF_UNICODETEXT, hmem):
                self._kernel32.GlobalFree(hmem)
                raise RuntimeError("SetClipboardData failed")
        finally:
            self._user32.CloseClipboard()

    def type_text(self, text: Any, use_clipboard: bool = False) -> None:
        self.check_stop()
        s = "" if text is None else str(text)
        preview = s.replace("\r", "\\r").replace("\n", "\\n")
        if len(preview) > 50:
            preview = preview[:47] + "..."
        self._step(f"type_text({preview!r}, clipboard={bool(use_clipboard)})")
        if self.dry_run or not s:
            return
        if use_clipboard:
            self._set_clipboard_text(s)
            self._sleep_ms_raw(20)
            self._key_press_raw(0x56, ctrl=True)
            self._sleep_ms_raw(30)
            return

        i = 0
        n = len(s)
        while i < n:
            self.check_stop()
            ch = s[i]
            if ch == "\r":
                if i + 1 < n and s[i + 1] == "\n":
                    i += 1
                self._key_press_raw(VK_RETURN)
            elif ch == "\n":
                self._key_press_raw(VK_RETURN)
            elif ch == "\t":
                self._key_press_raw(VK_TAB)
            else:
                u16 = ch.encode("utf-16-le")
                for j in range(0, len(u16), 2):
                    cu = int.from_bytes(u16[j : j + 2], "little")
                    self._send_unicode_unit(cu, key_up=False)
                    self._send_unicode_unit(cu, key_up=True)
            i += 1
            time.sleep(0.002)

